-- 1. SEQUENCES
CREATE SEQUENCE IF NOT EXISTS seq_PhieuNhap AS BIGINT START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS seq_HoaDon AS BIGINT START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS seq_BaoHanh AS BIGINT START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS seq_TraHang AS BIGINT START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS seq_TiepNhan AS BIGINT START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS seq_DonHang AS BIGINT START WITH 1 INCREMENT BY 1;

-- 2. TABLES

-- 2.1 BẢNG PHÂN QUYỀN
CREATE TABLE IF NOT EXISTS PhanQuyen (
    MAQUYEN  VARCHAR(10) PRIMARY KEY,
    TENQUYEN VARCHAR(50)  NOT NULL UNIQUE,
    MOTA     VARCHAR(255) NULL
);

-- 2.2 BẢNG NHÂN VIÊN
CREATE TABLE IF NOT EXISTS NhanVien (
    MANV       VARCHAR(10) PRIMARY KEY,
    HOTEN      VARCHAR(100) NOT NULL,
    CHUCVU     VARCHAR(50)  NOT NULL,
    SDT        VARCHAR(15)   NULL,
    EMAIL      VARCHAR(100) NULL,
    NGAYVAOLAM TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    TRANGTHAI  VARCHAR(10)   NOT NULL DEFAULT 'dang_lam',
    CONSTRAINT CK_NhanVien_ChucVu CHECK (CHUCVU IN ('Quản lý', 'Bán hàng', 'Thu ngân', 'Kho', 'Kỹ thuật & Bảo hành')),
    CONSTRAINT CK_NhanVien_TrangThai CHECK (TRANGTHAI IN ('dang_lam', 'da_nghi'))
);

-- 2.3 BẢNG TÀI KHOẢN
CREATE TABLE IF NOT EXISTS TaiKhoan (
    USERNAME      VARCHAR(50) PRIMARY KEY,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    MANV          VARCHAR(10)  NOT NULL UNIQUE REFERENCES NhanVien(MANV) ON DELETE CASCADE,
    MAQUYEN       VARCHAR(10)  NOT NULL REFERENCES PhanQuyen(MAQUYEN),
    TRANGTHAI     VARCHAR(10)  NOT NULL DEFAULT 'hoat_dong',
    NGAYTAO       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_TaiKhoan_TrangThai CHECK (TRANGTHAI IN ('hoat_dong', 'bi_khoa'))
);

-- 2.4 BẢNG NHÓM HÀNG
CREATE TABLE IF NOT EXISTS NhomHang (
    MANHOM  VARCHAR(10) PRIMARY KEY,
    TENNHOM VARCHAR(50) NOT NULL UNIQUE
);

-- 2.5 BẢNG LOẠI HÀNG
CREATE TABLE IF NOT EXISTS LoaiHang (
    MALOAI  VARCHAR(10) PRIMARY KEY,
    TENLOAI VARCHAR(50) NOT NULL UNIQUE
);

-- 2.6 BẢNG THUỘC TÍNH
CREATE TABLE IF NOT EXISTS ThuocTinh (
    MATHUOCTINH  VARCHAR(10) PRIMARY KEY,
    TENTHUOCTINH VARCHAR(50) NOT NULL
);

-- 2.7 BẢNG MẶT HÀNG
CREATE TABLE IF NOT EXISTS MatHang (
    MAHANG          VARCHAR(10) PRIMARY KEY,
    TENHANG         VARCHAR(100) NOT NULL,
    DONGIA          DECIMAL(18,2) NOT NULL CHECK (DONGIA > 0),
    DVT             VARCHAR(20)  NOT NULL DEFAULT 'Cái',
    MANHOM          VARCHAR(10)  NOT NULL REFERENCES NhomHang(MANHOM),
    MALOAI          VARCHAR(10)  NOT NULL REFERENCES LoaiHang(MALOAI),
    QUANLYIMEI      BOOLEAN      NOT NULL DEFAULT FALSE,
    THOIHANBAOHANH  INT          NOT NULL DEFAULT 0 CHECK (THOIHANBAOHANH >= 0)
);

-- 2.8 BẢNG CHI TIẾT THUỘC TÍNH
CREATE TABLE IF NOT EXISTS ChiTietThuocTinh (
    MAHANG      VARCHAR(10) REFERENCES MatHang(MAHANG) ON DELETE CASCADE,
    MATHUOCTINH VARCHAR(10) REFERENCES ThuocTinh(MATHUOCTINH) ON DELETE CASCADE,
    GIA_TRI     VARCHAR(100) NOT NULL,
    PRIMARY KEY (MAHANG, MATHUOCTINH)
);

-- 2.9 BẢNG NHÀ CUNG CẤP
CREATE TABLE IF NOT EXISTS NhaCungCap (
    MANCC  VARCHAR(10) PRIMARY KEY,
    TENNCC VARCHAR(100) NOT NULL,
    DIACHI VARCHAR(255) NULL,
    SDT    VARCHAR(15)  NULL,
    EMAIL  VARCHAR(100) NULL
);

-- 2.10 BẢNG PHIẾU NHẬP
CREATE TABLE IF NOT EXISTS PhieuNhap (
    SOPN     VARCHAR(15) PRIMARY KEY,
    NGAYNHAP TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MANCC    VARCHAR(10) NOT NULL REFERENCES NhaCungCap(MANCC),
    MANV     VARCHAR(10) NOT NULL REFERENCES NhanVien(MANV)
);

-- 2.11 BẢNG CHI TIẾT PHIẾU NHẬP
CREATE TABLE IF NOT EXISTS ChiTietPhieuNhap (
    SOPN        VARCHAR(15) REFERENCES PhieuNhap(SOPN) ON DELETE CASCADE,
    MAHANG      VARCHAR(10) REFERENCES MatHang(MAHANG),
    SLNHAP      INT           NOT NULL CHECK (SLNHAP > 0),
    DONGIA_NHAP DECIMAL(18,2) NOT NULL CHECK (DONGIA_NHAP > 0),
    PRIMARY KEY (SOPN, MAHANG)
);

-- 2.12 BẢNG IMEI
CREATE TABLE IF NOT EXISTS IMEI (
    MAIMEI    VARCHAR(20) PRIMARY KEY,
    MAHANG    VARCHAR(10) NOT NULL REFERENCES MatHang(MAHANG),
    SOPN      VARCHAR(15) NOT NULL REFERENCES PhieuNhap(SOPN),
    SOIMEI    VARCHAR(20) NOT NULL UNIQUE CHECK (LENGTH(SOIMEI) = 15 AND SOIMEI ~ '^[0-9]+$'),
    TRANGTHAI VARCHAR(20) NOT NULL DEFAULT 'con_hang' CHECK (TRANGTHAI IN ('con_hang', 'da_ban', 'tra_hang', 'cho_duyet', 'dang_sua')),
    CONSTRAINT UQ_IMEI_MaImei_MaHang UNIQUE (MAIMEI, MAHANG)
);

-- 2.13 BẢNG KHÁCH HÀNG
CREATE TABLE IF NOT EXISTS KhachHang (
    MAKH   VARCHAR(10) PRIMARY KEY,
    HOTEN  VARCHAR(100) NOT NULL,
    DIACHI VARCHAR(255) NULL,
    SDT    VARCHAR(15)  NULL,
    EMAIL  VARCHAR(100) NULL
);

-- 2.14 BẢNG KHUYẾN MÃI
CREATE TABLE IF NOT EXISTS KhuyenMai (
    MAKM         VARCHAR(10) PRIMARY KEY,
    TENKM        VARCHAR(100) NOT NULL,
    PHANTRAMGIAM DECIMAL(5,2) NOT NULL CHECK (PHANTRAMGIAM > 0 AND PHANTRAMGIAM <= 100),
    NGAYBD       TIMESTAMPTZ  NOT NULL,
    NGAYKT       TIMESTAMPTZ  NOT NULL CHECK (NGAYKT > NGAYBD),
    TAMDUNG      BOOLEAN      NOT NULL DEFAULT FALSE
);

-- 2.15 BẢNG HÓA ĐƠN
CREATE TABLE IF NOT EXISTS HoaDon (
    SOHD                VARCHAR(15) PRIMARY KEY,
    NGAYLAP             TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MAKH                VARCHAR(10)   NULL REFERENCES KhachHang(MAKH),
    MANV                VARCHAR(10)   NOT NULL REFERENCES NhanVien(MANV),
    MAKM                VARCHAR(10)   NULL REFERENCES KhuyenMai(MAKM),
    KENHBAN             VARCHAR(10)   NOT NULL DEFAULT 'tai_quay' CHECK (KENHBAN IN ('tai_quay', 'online')),
    TONGTIEN            DECIMAL(18,2) NOT NULL DEFAULT 0 CHECK (TONGTIEN >= 0),
    TIENGIAMGIA         DECIMAL(18,2) NOT NULL DEFAULT 0 CHECK (TIENGIAMGIA >= 0 AND TIENGIAMGIA <= TONGTIEN),
    THANHTIEN           DECIMAL(18,2) GENERATED ALWAYS AS (TONGTIEN - TIENGIAMGIA) STORED,
    PHUONGTHUCTHANHTOAN VARCHAR(20)   NOT NULL CHECK (PHUONGTHUCTHANHTOAN IN ('tien_mat', 'chuyen_khoan', 'the'))
);

-- 2.16 BẢNG CHI TIẾT HÓA ĐƠN
CREATE TABLE IF NOT EXISTS ChiTietHoaDon (
    MACTHD     SERIAL PRIMARY KEY,
    SOHD       VARCHAR(15)   NOT NULL REFERENCES HoaDon(SOHD) ON DELETE CASCADE,
    MAHANG     VARCHAR(10)   NOT NULL REFERENCES MatHang(MAHANG),
    MAIMEI     VARCHAR(20)   NULL REFERENCES IMEI(MAIMEI),
    SLBAN      INT           NOT NULL CHECK (SLBAN > 0),
    DONGIA_BAN DECIMAL(18,2) NOT NULL CHECK (DONGIA_BAN > 0),
    CONSTRAINT CK_CTHD_IMEI_SoLuong CHECK (MAIMEI IS NULL OR SLBAN = 1)
);

-- 2.17 BẢNG BẢO HÀNH
CREATE TABLE IF NOT EXISTS BaoHanh (
    MABH         VARCHAR(15) PRIMARY KEY,
    SOHD         VARCHAR(15)  NOT NULL REFERENCES HoaDon(SOHD),
    MAIMEI       VARCHAR(20)  NOT NULL UNIQUE REFERENCES IMEI(MAIMEI),
    NGAYBD       TIMESTAMPTZ  NOT NULL,
    THOIHANTHANG INT          NOT NULL CHECK (THOIHANTHANG > 0),
    NGAYKT       TIMESTAMPTZ  NULL,
    DIEUKIEN     VARCHAR(255) NULL
);

-- 2.18 BẢNG TRẢ HÀNG
CREATE TABLE IF NOT EXISTS TraHang (
    MATR                 VARCHAR(15) PRIMARY KEY,
    SOHD                 VARCHAR(15)   NOT NULL REFERENCES HoaDon(SOHD),
    MAIMEI               VARCHAR(20)   NOT NULL REFERENCES IMEI(MAIMEI),
    LOAIYEUCAU           VARCHAR(20)   NOT NULL DEFAULT 'loi_ky_thuat' CHECK (LOAIYEUCAU IN ('loi_ky_thuat', 'doi_y')),
    HINHTHUCHOANTIEN     VARCHAR(20)   NOT NULL CHECK (HINHTHUCHOANTIEN IN ('tien_mat', 'chuyen_khoan', 'doi_hang')),
    LYDO                 VARCHAR(255)  NOT NULL,
    TRANGTHAI            VARCHAR(20)   NOT NULL DEFAULT 'tiep_nhan' CHECK (TRANGTHAI IN ('tiep_nhan', 'da_kiem_tra', 'da_duyet', 'tu_choi', 'hoan_tat', 'da_huy')),
    NGAYTR               TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MANV                 VARCHAR(10)   NOT NULL REFERENCES NhanVien(MANV),
    CHECKLIST_NGOAIQUAN  TEXT          NULL,
    KETQUA_KIEMTRA       VARCHAR(30)   NULL CHECK (KETQUA_KIEMTRA IS NULL OR KETQUA_KIEMTRA IN ('loi_nsx', 'khong_loi', 'hu_hong_do_nguoi_dung')),
    GHICHU_KIEMTRA       TEXT          NULL,
    MANV_KIEMTRA         VARCHAR(10)   NULL REFERENCES NhanVien(MANV),
    NGAY_KIEMTRA         TIMESTAMPTZ   NULL,
    MANV_DUYET           VARCHAR(10)   NULL REFERENCES NhanVien(MANV),
    NGAY_DUYET           TIMESTAMPTZ   NULL,
    LYDO_TUCHOI          VARCHAR(255)  NULL,
    SOTIENHOAN           DECIMAL(18,2) NULL CHECK (SOTIENHOAN IS NULL OR SOTIENHOAN >= 0),
    MAGIAODICH           VARCHAR(50)   NULL,
    MAIMEI_MOI           VARCHAR(20)   NULL REFERENCES IMEI(MAIMEI),
    MANV_HOANTAT         VARCHAR(10)   NULL REFERENCES NhanVien(MANV),
    NGAY_HOANTAT         TIMESTAMPTZ   NULL
);

-- Partial Unique Index: Khong cho 2 phieu cung IMEI o trang thai dang mo hoac hoan tat
CREATE UNIQUE INDEX IF NOT EXISTS UQ_TraHang_Active_IMEI ON TraHang(MAIMEI)
    WHERE TRANGTHAI NOT IN ('tu_choi', 'da_huy');

-- 2.18b BẢNG NHẬT KÝ ĐỔI TRẢ (AUDIT LOG)
CREATE TABLE IF NOT EXISTS TraHangLichSu (
    MALICHSU       BIGSERIAL PRIMARY KEY,
    MATR           VARCHAR(15)  NOT NULL REFERENCES TraHang(MATR) ON DELETE CASCADE,
    TRANGTHAI_CU   VARCHAR(20)  NULL,
    TRANGTHAI_MOI  VARCHAR(20)  NOT NULL,
    MANV           VARCHAR(10)  NOT NULL REFERENCES NhanVien(MANV),
    THOIDIEM       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    GHICHU         VARCHAR(255) NULL
);
CREATE INDEX IF NOT EXISTS IX_TraHangLichSu_MaTR ON TraHangLichSu(MATR);

-- 2.19 BẢNG PHIẾU TIẾP NHẬN BẢO HÀNH
CREATE TABLE IF NOT EXISTS PhieuTiepNhanBaoHanh (
    MATN          VARCHAR(15) PRIMARY KEY,
    MABH          VARCHAR(15)   NOT NULL REFERENCES BaoHanh(MABH),
    NGAYNHAN      TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    TINHTRANGLOI  VARCHAR(255)  NOT NULL,
    MANV_TIEPNHAN VARCHAR(10)   NOT NULL REFERENCES NhanVien(MANV),
    MANV_KYTHUAT  VARCHAR(10)   NULL REFERENCES NhanVien(MANV),
    NGAYHENTRA    TIMESTAMPTZ   NULL CHECK (NGAYHENTRA IS NULL OR NGAYHENTRA >= NGAYNHAN),
    NGAYTRA       TIMESTAMPTZ   NULL CHECK (NGAYTRA IS NULL OR NGAYTRA >= NGAYNHAN),
    KETQUA        VARCHAR(255)  NULL,
    CHIPHI        DECIMAL(18,2) NOT NULL DEFAULT 0 CHECK (CHIPHI >= 0),
    TRANGTHAI     VARCHAR(20)   NOT NULL DEFAULT 'tiep_nhan' CHECK (TRANGTHAI IN ('tiep_nhan', 'dang_sua', 'cho_linh_kien', 'hoan_thanh', 'da_tra'))
);

-- 2.20 BẢNG ĐƠN HÀNG ONLINE
CREATE TABLE IF NOT EXISTS DonHangOnline (
    MADH                VARCHAR(15) PRIMARY KEY,
    NGAYDAT             TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MAKH                VARCHAR(10)   NOT NULL REFERENCES KhachHang(MAKH),
    TENNGUOINHAN        VARCHAR(100)  NOT NULL,
    SDTNGUOINHAN        VARCHAR(15)   NOT NULL,
    DIACHIGIAO          VARCHAR(255)  NOT NULL,
    PHUONGTHUCTHANHTOAN VARCHAR(20)   NOT NULL CHECK (PHUONGTHUCTHANHTOAN IN ('cod', 'chuyen_khoan', 'the')),
    TONGTIEN            DECIMAL(18,2) NOT NULL DEFAULT 0 CHECK (TONGTIEN >= 0),
    TRANGTHAI           VARCHAR(20)   NOT NULL DEFAULT 'cho_xac_nhan' CHECK (TRANGTHAI IN ('cho_thanh_toan', 'cho_xac_nhan', 'da_xac_nhan', 'dang_giao', 'hoan_thanh', 'da_huy')),
    MANV                VARCHAR(10)   NULL REFERENCES NhanVien(MANV),
    SOHD                VARCHAR(15)   NULL REFERENCES HoaDon(SOHD)
);

-- 2.21 BẢNG CHI TIẾT ĐƠN HÀNG ONLINE
CREATE TABLE IF NOT EXISTS ChiTietDonHangOnline (
    MADH    VARCHAR(15) REFERENCES DonHangOnline(MADH) ON DELETE CASCADE,
    MAHANG  VARCHAR(10) REFERENCES MatHang(MAHANG),
    SOLUONG INT           NOT NULL CHECK (SOLUONG > 0),
    DONGIA  DECIMAL(18,2) NOT NULL CHECK (DONGIA > 0),
    PRIMARY KEY (MADH, MAHANG)
);

-- 2.22 BẢNG THAM SỐ
CREATE TABLE IF NOT EXISTS ThamSo (
    MATHAMSO  VARCHAR(30) PRIMARY KEY,
    TENTHAMSO VARCHAR(100) NOT NULL,
    GIATRI    DECIMAL(18,2) NOT NULL CHECK (GIATRI >= 0),
    DONVI     VARCHAR(20)  NULL
);

-- 3. INDEXES
CREATE UNIQUE INDEX IF NOT EXISTS UX_NhanVien_Email ON NhanVien(EMAIL) WHERE EMAIL IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS UX_KhachHang_SDT ON KhachHang(SDT) WHERE SDT IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS UX_CTHD_MaImei ON ChiTietHoaDon(MAIMEI) WHERE MAIMEI IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS UX_CTHD_HoaDon_MatHang ON ChiTietHoaDon(SOHD, MAHANG) WHERE MAIMEI IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS UX_TiepNhan_DangMo ON PhieuTiepNhanBaoHanh(MABH) WHERE TRANGTHAI IN ('tiep_nhan', 'dang_sua', 'cho_linh_kien');
CREATE UNIQUE INDEX IF NOT EXISTS UX_DHOL_SoHD ON DonHangOnline(SOHD) WHERE SOHD IS NOT NULL;

CREATE INDEX IF NOT EXISTS IX_MatHang_NhomHang ON MatHang(MANHOM);
CREATE INDEX IF NOT EXISTS IX_MatHang_LoaiHang ON MatHang(MALOAI);
CREATE INDEX IF NOT EXISTS IX_PhieuNhap_NhaCungCap ON PhieuNhap(MANCC);
CREATE INDEX IF NOT EXISTS IX_IMEI_MatHang_TrangThai ON IMEI(MAHANG, TRANGTHAI);
CREATE INDEX IF NOT EXISTS IX_IMEI_PhieuNhap ON IMEI(SOPN);
CREATE INDEX IF NOT EXISTS IX_HoaDon_NgayLap ON HoaDon(NGAYLAP);
CREATE INDEX IF NOT EXISTS IX_HoaDon_KhachHang ON HoaDon(MAKH);
CREATE INDEX IF NOT EXISTS IX_HoaDon_NhanVien ON HoaDon(MANV);
CREATE INDEX IF NOT EXISTS IX_HoaDon_KhuyenMai ON HoaDon(MAKM);
CREATE INDEX IF NOT EXISTS IX_CTHD_HoaDon ON ChiTietHoaDon(SOHD);
CREATE INDEX IF NOT EXISTS IX_CTHD_MatHang ON ChiTietHoaDon(MAHANG);
CREATE INDEX IF NOT EXISTS IX_BaoHanh_HoaDon ON BaoHanh(SOHD);
CREATE INDEX IF NOT EXISTS IX_TraHang_HoaDon ON TraHang(SOHD);
CREATE INDEX IF NOT EXISTS IX_DHOL_KhachHang ON DonHangOnline(MAKH);
CREATE INDEX IF NOT EXISTS IX_DHOL_TrangThai ON DonHangOnline(TRANGTHAI);

